#!/usr/bin/env python3
"""Regenerate channels.generated.js from curation/channels.yaml.

The Worker bakes its known-channel list in at deploy time rather than
fetching channels.yaml live (ticket #114, part of #113). Re-run this and
commit the result after any change to curation/channels.yaml.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "curation"))

from pipeline import load_channel_display_names  # noqa: E402

OUTPUT_FILE = Path(__file__).resolve().parent / "channels.generated.js"


def main():
    # The Worker validates and counts by Channel (display_name), not by
    # curation source key — several source keys can share one Channel
    # (e.g. fenkil/fenkil_diaspora both display as "Fenkil"), and counting
    # by source key would fragment a single Channel's watches across keys
    # that never get reaggregated anywhere downstream.
    channels = load_channel_display_names()
    lines = [
        "// Generated by worker/generate_channels.py from curation/channels.yaml.",
        "// Do not edit by hand — re-run the script and commit the result.",
        "export const KNOWN_CHANNELS = [",
        *(f"  {json.dumps(channel)}," for channel in channels),
        "];",
        "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
